using System;
using System.Linq;
using TrafficGame.App.Platform;
using TrafficGame.Core.Levels;
using TrafficGame.Core.Roads;
using TrafficGame.Presentation.Cameras;
using TrafficGame.Presentation.Levels;
using TrafficGame.Presentation.Localization;
using TrafficGame.Presentation.Platform;
using TrafficGame.Presentation.Settings;
using TrafficGame.Views.Cameras;
using TrafficGame.Views.Debugging;
using TrafficGame.Views.Rendering;
using Unity.Mathematics;
using UnityEngine;

namespace TrafficGame.App
{
    /// <summary>
    /// Composition root and app flow: creates the long-lived services and views, shows the title menu over a live
    /// showcase map, and opens/closes <see cref="LevelSession"/>s as the player moves between levels.
    /// The scene itself is generated by the editor menu <c>Traffic Game → Rebuild Game Scene</c>.
    /// </summary>
    public sealed class GameBootstrap : MonoBehaviour
    {
        private const string ProgressKey = "progress";
        private const string ThemeKey = "theme";

        /// <summary>Width of the menu side sheet in UI units (<c>.menu__sheet</c> in Game.uss).</summary>
        private const float MenuSheetWidth = 500f;

        /// <summary>Share of a portrait screen the menu's bottom sheet covers, roughly.</summary>
        private const float MenuSheetPortraitShare = 0.6f;
        private const string SandboxId = "sandbox";

        [SerializeField] private GameConfig _config;
        [SerializeField] private CameraView _cameraView;
        [SerializeField] private CameraInputAdapter _cameraInput;
        [SerializeField] private CheckerGroundView _ground;
        [SerializeField] private SessionViews _views;

        private IPlatformService _platform;
        private Browser _browser;
        private MapTheme _mapTheme;
        private ThemePresenter _theme;
        private CameraPresenter _camera;
        private RoadProfileCatalog _profiles;
        private (string id, LevelData data)[] _campaign;
        private LevelData _sandbox;
        private PlayerProgress _progress;
        private MenuPresenter _menu;
        private LevelSession _session;
        private string _currentLevelId;
        private bool _playing;
        private bool _changingScene;

        private void Awake()
        {
            _browser = new Browser();
            _mapTheme = new MapTheme(_config, _ground, _cameraView.GetComponent<Camera>(), new IMapPaletteView[]
            {
                _views.Roads, _views.Preview, _views.Buildings, _views.Congestion, _views.JunctionControls
            });
            // The saved theme choice is known only once the platform is ready; until then follow the system.
            _mapTheme.ApplyTheme(_browser.PrefersDark);

            _cameraInput.Configure(_config.ScrollZoomSensitivity);
            _camera = new CameraPresenter(_cameraView, _cameraInput, _views.Frames, _config.CameraSettings, float2.zero);

            _profiles = _config.CreateRoadProfileCatalog();
            _campaign = _config.CampaignLevels.Select(file => (file.name, LevelSerializer.Deserialize(file.text))).ToArray();
            _sandbox = LevelSerializer.Deserialize(_config.SandboxLevel.text);

            _platform = new PrimePlatformService();
            _platform.Initialize(OnPlatformReady);
        }

        private void Update()
        {
            _browser?.Update(Time.unscaledDeltaTime);
            _mapTheme?.Update(Time.unscaledDeltaTime);
        }

        private void OnDestroy()
        {
            _theme?.Dispose();
            _session?.Dispose();
            _menu?.Dispose();
            _camera?.Dispose();
        }

        /// <summary>The UI needs the platform language and saved progress, so the flow starts once the SDK is ready.</summary>
        private void OnPlatformReady()
        {
            var localizer = new JsonLocalizer(_config.LanguageFiles, _config.FallbackLanguage);
            localizer.SetLanguage(_platform.LanguageCode);

            var ui = _views.Ui;
            ui.Initialize(localizer, _cameraView.GetComponent<Camera>());
            _cameraInput.SetUiHitTest(ui);
            _views.Pointer.SetUiHitTest(ui);

            _theme = new ThemePresenter(_browser, ui.ThemeControl, new IThemeView[] { ui, _mapTheme },
                ThemePresenter.Parse(_platform.LoadString(ThemeKey, string.Empty)));
            _theme.ModeChanged += mode =>
            {
                _platform.SaveString(ThemeKey, mode.ToString());
                _platform.Flush();
            };

            _progress = PlayerProgress.FromJson(_platform.LoadString(ProgressKey, string.Empty));
            _menu = new MenuPresenter(ui.Menu, _campaign.Select(level => CreateLevel(level.id, level.data)).ToArray(), _progress);
            _menu.LevelChosen += level => OpenLevel(level.Id);
            _menu.SandboxChosen += OpenSandbox;

            OpenMenu();
            ui.RevealScene();
            _platform.NotifyGameReady();
        }

        private void ShowMenu() => ChangeScene(OpenMenu);

        /// <summary>Swaps what is on the map behind the UI's curtain; requests arriving while one is under way are dropped.</summary>
        private void ChangeScene(Action change)
        {
            if (_changingScene)
                return;

            _changingScene = true;
            _views.Ui.ChangeScene(() =>
            {
                _changingScene = false;
                change();
            });
        }

        private void OpenMenu()
        {
            SetPlaying(false);
            var showcase = CreateLevel(SandboxId, _sandbox);
            OpenSession(showcase, 0, SessionMode.Showcase, hasNextLevel: false);
            FrameBesideMenu(showcase);
            _menu.Show();
        }

        /// <summary>Moves the showcase map out from under the menu sheet: to its right in landscape, above it in portrait.</summary>
        private void FrameBesideMenu(Level level)
        {
            var center = level.CameraCenter ?? float2.zero;
            var halfHeight = level.CameraHalfHeight ?? _config.CameraSettings.InitialHalfHeight;
            var aspect = (float)Screen.width / Mathf.Max(Screen.height, 1);
            if (aspect >= 1f)
            {
                var covered = Mathf.Clamp01(MenuSheetWidth * _views.Ui.ScreenPixelsPerUnit / Mathf.Max(Screen.width, 1));
                center.x -= halfHeight * aspect * covered;
            }
            else
            {
                center.y -= halfHeight * MenuSheetPortraitShare;
            }

            _camera.Focus(center, halfHeight, CameraMove.Arrive);
        }

        private void OpenLevel(string id)
        {
            if (_changingScene)
                return;

            var index = Array.FindIndex(_campaign, level => level.id == id);
            _currentLevelId = id;
            _menu.Hide();
            ChangeScene(() =>
                OpenSession(CreateLevel(id, _campaign[index].data), index + 1, SessionMode.Play, hasNextLevel: index + 1 < _campaign.Length));
        }

        private void OpenSandbox()
        {
            if (_changingScene)
                return;

            _currentLevelId = null;
            _menu.Hide();
            ChangeScene(() => OpenSession(CreateLevel(SandboxId, _sandbox), 0, SessionMode.Play, hasNextLevel: false));
        }

        private void OpenSession(Level level, int levelNumber, SessionMode mode, bool hasNextLevel)
        {
            _session?.Dispose();
            _session = new LevelSession(level, levelNumber, mode, hasNextLevel, _config, _profiles, _views, _camera);
            if (mode != SessionMode.Play)
                return;

            _session.GameplayStarted += () => SetPlaying(true);
            _session.Completed += OnLevelCompleted;
            _session.RetryRequested += Retry;
            _session.NextRequested += OpenNextLevel;
            _session.MenuRequested += ShowMenu;
            if (_session.StartsImmediately)
                SetPlaying(true);
        }

        private void Retry()
        {
            if (_platform.IsReady)
                _platform.NotifyGameplayRestarted();
            if (_currentLevelId != null)
                OpenLevel(_currentLevelId);
            else
                OpenSandbox();
        }

        private void OnLevelCompleted(int stars)
        {
            SetPlaying(false);
            _platform.Celebrate();
            if (_currentLevelId == null || !_progress.Record(_currentLevelId, stars))
                return;

            _platform.SaveString(ProgressKey, _progress.ToJson());
            _platform.Flush();
        }

        private void OpenNextLevel()
        {
            var index = Array.FindIndex(_campaign, level => level.id == _currentLevelId);
            if (index >= 0 && index + 1 < _campaign.Length)
                OpenLevel(_campaign[index + 1].id);
            else
                ShowMenu();
        }

        /// <summary>Reports gameplay start/stop to the platform exactly once per change.</summary>
        private void SetPlaying(bool playing)
        {
            if (playing == _playing || !_platform.IsReady)
                return;

            _playing = playing;
            if (playing)
                _platform.NotifyGameplayStarted();
            else
                _platform.NotifyGameplayStopped();
        }

        /// <summary>Levels are rebuilt from their data every time, so each session starts from a clean network.</summary>
        private Level CreateLevel(string id, LevelData data) => LevelSerializer.CreateLevel(id, data, _profiles);
    }
}
